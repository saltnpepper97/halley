/// Per-resource data for an advertised workspace group handle.
#[derive(Clone, Copy, Debug)]
pub struct GroupData {
    /// Identifies the manager binding that owns this handle.
    pub binding: u64,
}

/// Per-resource data for an advertised workspace handle.
#[derive(Clone, Copy, Debug)]
pub struct WorkspaceData {
    /// Identifies the manager binding that owns this handle.
    pub binding: u64,
    pub cluster: ClusterId,
}

struct GroupBinding {
    output: Output,
    handle: ExtWorkspaceGroupHandleV1,
    /// Set once the client destroyed the handle. The entry survives because it
    /// still records membership: a client that drops the group object keeps the
    /// workspace handles it already holds, and the dead object is never used
    /// again.
    detached: bool,
    /// `wl_output` resources already associated with this group, keyed by
    /// object id so a late bind can never double-send `output_enter`.
    outputs: HashMap<ObjectId, WlOutput>,
    /// Clusters currently advertised as members of this group.
    workspaces: Vec<ClusterId>,
}

struct WorkspaceBinding {
    cluster: ClusterId,
    handle: ExtWorkspaceHandleV1,
    /// Group this workspace is a member of, by output identity.
    group: Option<Output>,
    name: String,
    order: u8,
    active: bool,
    /// The client destroyed this handle: stop advertising the cluster to this
    /// binding instead of recreating the object on every synchronisation.
    detached: bool,
}

struct Binding {
    id: u64,
    client: Client,
    manager: ExtWorkspaceManagerV1,
    groups: Vec<GroupBinding>,
    workspaces: Vec<WorkspaceBinding>,
    pending: Vec<PendingRequest>,
}

/// All `ext-workspace-v1` protocol state.
pub struct State {
    _global: GlobalId,
    next_binding: u64,
    bindings: Vec<Binding>,
}

impl State {
    pub fn new<D>(display: &DisplayHandle) -> Self
    where
        D: GlobalDispatch<ExtWorkspaceManagerV1, ()> + 'static,
    {
        Self {
            _global: display.create_global::<D, ExtWorkspaceManagerV1, _>(VERSION, ()),
            next_binding: 1,
            bindings: Vec::new(),
        }
    }

    /// True when no client is listening, so the session can skip snapshot work.
    pub fn is_idle(&self) -> bool {
        self.bindings.is_empty()
    }

    fn next_binding_id(&mut self) -> u64 {
        let id = self.next_binding;
        self.next_binding += 1;
        id
    }

    /// Registers a new manager binding and advertises the current snapshot.
    ///
    /// `sync` also runs at the event-loop boundary, but advertising here keeps a
    /// client that round-trips immediately after binding from observing an
    /// empty compositor.
    pub fn bind<D>(
        &mut self,
        display: &DisplayHandle,
        client: &Client,
        manager: ExtWorkspaceManagerV1,
        snapshot: &Snapshot,
    ) where
        D: Dispatch<ExtWorkspaceGroupHandleV1, GroupData>
            + Dispatch<ExtWorkspaceHandleV1, WorkspaceData>
            + 'static,
    {
        let id = self.next_binding_id();
        let mut binding = Binding {
            id,
            client: client.clone(),
            manager,
            groups: Vec::new(),
            workspaces: Vec::new(),
            pending: Vec::new(),
        };
        sync_binding::<D>(display, &mut binding, snapshot);
        self.bindings.push(binding);
    }

    /// Pushes the snapshot to every live binding.
    ///
    /// Returns whether any event was sent. An unchanged snapshot sends nothing,
    /// so this is safe to call unconditionally at the event-loop boundary.
    pub fn sync<D>(&mut self, display: &DisplayHandle, snapshot: &Snapshot) -> bool
    where
        D: Dispatch<ExtWorkspaceGroupHandleV1, GroupData>
            + Dispatch<ExtWorkspaceHandleV1, WorkspaceData>
            + 'static,
    {
        if self.bindings.is_empty() {
            return false;
        }
        let mut sent = false;
        for binding in &mut self.bindings {
            sent |= sync_binding::<D>(display, binding, snapshot);
        }
        sent
    }

    /// Associates a late `wl_output` bind with the groups of the same client.
    pub fn output_bound(&mut self, client: &Client, output: &Output, wl_output: &WlOutput) {
        let object = wl_output.id();
        for binding in &mut self.bindings {
            if binding.client.id() != client.id() {
                continue;
            }
            let mut touched = false;
            for group in &mut binding.groups {
                if group.detached || group.output != *output || group.outputs.contains_key(&object)
                {
                    continue;
                }
                group.handle.output_enter(wl_output);
                group.outputs.insert(object.clone(), wl_output.clone());
                touched = true;
            }
            if touched {
                binding.manager.done();
            }
        }
    }

    /// Queues one supported request. Nothing changes before `commit`.
    pub fn queue(&mut self, binding: u64, request: PendingRequest) {
        if let Some(binding) = self.binding_mut(binding) {
            binding.pending.push(request);
        }
    }

    /// Reduces and clears the queued transaction for one binding.
    ///
    /// Returns `None` when the binding is gone or nothing applicable was queued.
    pub fn commit(
        &mut self,
        binding: u64,
        owner_of: impl Fn(ClusterId) -> Option<String>,
        active_on: impl Fn(&str) -> Option<ClusterId>,
    ) -> Option<TransactionPlan> {
        let binding = self.binding_mut(binding)?;
        let requests = std::mem::take(&mut binding.pending);
        if requests.is_empty() {
            return None;
        }
        // A request is applied only while its cluster is still advertised to
        // this binding *through the object the request arrived on*. A destroyed
        // or superseded handle is therefore discarded instead of acted on.
        let advertised = binding
            .workspaces
            .iter()
            .filter(|workspace| !workspace.detached)
            .map(|workspace| (workspace.cluster, Resource::id(&workspace.handle)))
            .collect::<Vec<_>>();
        let live_clusters = advertised
            .iter()
            .map(|(cluster, _)| *cluster)
            .collect::<Vec<_>>();
        // The owner must still have a mapped output advertised to this binding,
        // so a cluster whose output vanished cannot be switched through a stale
        // handle. A group the client destroyed still counts as mapped: only the
        // group object was declined, not the output.
        let groups = binding
            .groups
            .iter()
            .map(|group| group.output.name())
            .collect::<Vec<_>>();
        let owned = |cluster: ClusterId| {
            let output = owner_of(cluster)?;
            groups.contains(&output).then_some(output)
        };

        let applicable = requests
            .iter()
            .filter(|request| advertised.contains(&(request.cluster, request.object.clone())))
            .map(|request| (request.cluster, request.action))
            .collect::<Vec<_>>();
        let plan = reduce_transaction(
            &applicable,
            |cluster| live_clusters.contains(&cluster),
            owned,
            active_on,
        );
        (!plan.is_empty() || plan.focus.is_some()).then_some(plan)
    }

    /// Handles `ext_workspace_manager_v1.stop`: discard pending work and finish
    /// the binding.
    pub fn manager_stopped(&mut self, binding_id: u64) {
        if let Some(binding) = self.binding_mut(binding_id) {
            binding.pending.clear();
            binding.manager.finished();
        }
        self.remove_binding(binding_id);
    }

    /// Drops one manager binding.
    ///
    /// Called for `stop` and for the manager object's `destroyed` callback,
    /// which wayland-server also runs for every object of a disconnecting
    /// client. The cluster records themselves are never touched.
    pub fn remove_binding(&mut self, binding_id: u64) {
        self.bindings.retain(|binding| binding.id != binding_id);
    }

    /// Handles destruction of a group handle: stop sending events to it without
    /// forgetting which workspaces belong to it.
    pub fn group_destroyed(&mut self, binding: u64, handle: &ExtWorkspaceGroupHandleV1) {
        let Some(binding) = self.binding_mut(binding) else {
            return;
        };
        let object = handle.id();
        if let Some(group) = binding
            .groups
            .iter_mut()
            .find(|group| Resource::id(&group.handle) == object)
        {
            group.detached = true;
            group.outputs.clear();
        }
    }

    /// Handles destruction of a workspace handle: retire the cluster from this
    /// binding without touching Halley's cluster record.
    pub fn workspace_destroyed(&mut self, binding: u64, handle: &ExtWorkspaceHandleV1) {
        let Some(binding) = self.binding_mut(binding) else {
            return;
        };
        let object = Resource::id(handle);
        let Some(workspace) = binding
            .workspaces
            .iter_mut()
            .find(|workspace| Resource::id(&workspace.handle) == object)
        else {
            return;
        };
        workspace.detached = true;
        let cluster = workspace.cluster;
        for group in &mut binding.groups {
            group.workspaces.retain(|candidate| *candidate != cluster);
        }
        binding.pending.retain(|request| request.object != object);
    }

    /// Resolves a manager resource back to its binding.
    pub fn binding_of(&self, client: &ClientId, manager: &ExtWorkspaceManagerV1) -> Option<u64> {
        let object = manager.id();
        self.bindings
            .iter()
            .find(|binding| {
                binding.client.id() == *client && Resource::id(&binding.manager) == object
            })
            .map(|binding| binding.id)
    }

    fn binding_mut(&mut self, id: u64) -> Option<&mut Binding> {
        self.bindings.iter_mut().find(|binding| binding.id == id)
    }
}

// ---------------------------------------------------------------------------
// Snapshot synchronisation
// ---------------------------------------------------------------------------

/// Reconciles one binding against the snapshot and emits only what changed.
/// Returns whether anything was sent.
fn sync_binding<D>(display: &DisplayHandle, binding: &mut Binding, snapshot: &Snapshot) -> bool
where
    D: Dispatch<ExtWorkspaceGroupHandleV1, GroupData>
        + Dispatch<ExtWorkspaceHandleV1, WorkspaceData>
        + 'static,
{
    let Binding {
        id,
        client,
        manager,
        groups,
        workspaces,
        pending,
    } = binding;
    let mut touched = false;

    // 1. Retire groups whose output is gone, or whose output was replaced by a
    //    new incarnation under the same name. Membership removal is emitted
    //    before the group is removed, as the protocol requires.
    let mut index = 0;
    while index < groups.len() {
        let stale = !snapshot
            .groups
            .iter()
            .any(|candidate| candidate.output == groups[index].output);
        if !stale {
            index += 1;
            continue;
        }
        let mut group = groups.remove(index);
        if !group.detached {
            for cluster in group.workspaces.iter() {
                if let Some(workspace) = workspaces
                    .iter()
                    .find(|workspace| workspace.cluster == *cluster && !workspace.detached)
                {
                    group.handle.workspace_leave(&workspace.handle);
                }
            }
            for output in group.outputs.values().filter(|output| output.is_alive()) {
                group.handle.output_leave(output);
            }
            group.handle.removed();
        }
        for cluster in group.workspaces.iter() {
            if let Some(workspace) = workspaces
                .iter_mut()
                .find(|workspace| workspace.cluster == *cluster)
            {
                workspace.group = None;
            }
        }
        group.outputs.clear();
        touched = true;
    }

    // 2. Retire workspaces orphaned by stale groups before synchronising any
    //    replacement groups. Pending requests are tied to the retired object,
    //    and a replacement output incarnation always gets fresh handles.
    let mut index = 0;
    while index < workspaces.len() {
        if workspaces[index].group.is_some() {
            index += 1;
            continue;
        }
        let workspace = workspaces.remove(index);
        let object = Resource::id(&workspace.handle);
        pending.retain(|request| request.object != object);
        if !workspace.detached {
            workspace.handle.removed();
        }
        touched = true;
    }

    // 3. Advertise and update the groups that should exist.
    for snapshot_group in &snapshot.groups {
        index = match groups
            .iter()
            .position(|group| group.output == snapshot_group.output)
        {
            Some(index) => index,
            None => {
                let Ok(handle) = client.create_resource::<ExtWorkspaceGroupHandleV1, _, D>(
                    display,
                    VERSION,
                    GroupData { binding: *id },
                ) else {
                    continue;
                };
                manager.workspace_group(&handle);
                handle.capabilities(GROUP_CAPABILITIES);
                groups.push(GroupBinding {
                    output: snapshot_group.output.clone(),
                    handle,
                    detached: false,
                    outputs: HashMap::new(),
                    workspaces: Vec::new(),
                });
                touched = true;
                groups.len() - 1
            }
        };

        touched |= sync_group::<D>(
            display,
            client,
            *id,
            groups,
            index,
            workspaces,
            manager,
            snapshot_group,
        );
    }

    // 4. Retire workspaces their output no longer advertises. The client-side
    //    handles become inert; a later re-advertisement uses a fresh object.
    let mut index = 0;
    while index < workspaces.len() {
        let retire = workspaces[index].group.is_none() && !workspaces[index].detached;
        if !retire {
            index += 1;
            continue;
        }
        workspaces.remove(index).handle.removed();
        touched = true;
    }

    if touched {
        manager.done();
    }
    touched
}

#[allow(clippy::too_many_arguments)]
fn sync_group<D>(
    display: &DisplayHandle,
    client: &Client,
    binding: u64,
    groups: &mut Vec<GroupBinding>,
    index: usize,
    workspaces: &mut Vec<WorkspaceBinding>,
    manager: &ExtWorkspaceManagerV1,
    snapshot: &GroupSnapshot,
) -> bool
where
    D: Dispatch<ExtWorkspaceGroupHandleV1, GroupData>
        + Dispatch<ExtWorkspaceHandleV1, WorkspaceData>
        + 'static,
{
    let mut touched = false;
    let detached = groups[index].detached;

    // `wl_output` association. `output_bound` covers the common case, but a
    // client that binds wl_output before the manager, or binds it twice, is
    // reconciled here.
    if !detached {
        groups[index].outputs.retain(|_, output| output.is_alive());
        let bound = snapshot
            .output
            .client_outputs(client)
            .map(|output| (output.id(), output))
            .collect::<Vec<_>>();
        for (object, output) in bound {
            if groups[index].outputs.contains_key(&object) {
                continue;
            }
            groups[index].handle.output_enter(&output);
            groups[index].outputs.insert(object, output);
            touched = true;
        }
    }

    // Members this group no longer advertises leave the group before anything
    // else references them.
    let stale = groups[index]
        .workspaces
        .iter()
        .copied()
        .filter(|cluster| !snapshot.workspaces.iter().any(|entry| entry.id == *cluster))
        .collect::<Vec<_>>();
    for cluster in stale {
        if let Some(workspace) = workspaces
            .iter()
            .find(|workspace| workspace.cluster == cluster && !workspace.detached)
        {
            if !detached {
                groups[index].handle.workspace_leave(&workspace.handle);
            }
            touched = true;
        }
        if let Some(workspace) = workspaces
            .iter_mut()
            .find(|workspace| workspace.cluster == cluster)
        {
            workspace.group = None;
        }
        groups[index]
            .workspaces
            .retain(|candidate| *candidate != cluster);
    }

    for entry in &snapshot.workspaces {
        let existing = workspaces
            .iter()
            .position(|workspace| workspace.cluster == entry.id);
        let Some(position) = existing else {
            let Ok(handle) = client.create_resource::<ExtWorkspaceHandleV1, _, D>(
                display,
                VERSION,
                WorkspaceData {
                    binding,
                    cluster: entry.id,
                },
            ) else {
                continue;
            };
            manager.workspace(&handle);
            handle.capabilities(WORKSPACE_CAPABILITIES);
            handle.name(entry.name.clone());
            handle.coordinates(coordinates(entry.order));
            handle.state(state_of(entry.active));
            if !detached {
                groups[index].handle.workspace_enter(&handle);
            }
            groups[index].workspaces.push(entry.id);
            workspaces.push(WorkspaceBinding {
                cluster: entry.id,
                handle,
                group: Some(snapshot.output.clone()),
                name: entry.name.clone(),
                order: entry.order,
                active: entry.active,
                detached: false,
            });
            touched = true;
            continue;
        };

        if workspaces[position].detached {
            // The client destroyed this object; do not recreate it.
            continue;
        }

        // A cluster that moved between outputs changes group before its
        // properties are refreshed, so a client never sees it in two groups.
        if workspaces[position].group.as_ref() != Some(&snapshot.output) {
            let previous = workspaces[position].group.clone();
            if let Some(previous) = previous
                && let Some(old) = groups
                    .iter_mut()
                    .find(|group| group.output == previous && !group.detached)
            {
                old.handle.workspace_leave(&workspaces[position].handle);
                old.workspaces.retain(|candidate| *candidate != entry.id);
            }
            workspaces[position].group = Some(snapshot.output.clone());
            if !detached {
                groups[index]
                    .handle
                    .workspace_enter(&workspaces[position].handle);
            }
            touched = true;
        }

        let handle = workspaces[position].handle.clone();
        if workspaces[position].name != entry.name {
            workspaces[position].name = entry.name.clone();
            handle.name(entry.name.clone());
            touched = true;
        }
        if workspaces[position].order != entry.order {
            workspaces[position].order = entry.order;
            handle.coordinates(coordinates(entry.order));
            touched = true;
        }
        if workspaces[position].active != entry.active {
            workspaces[position].active = entry.active;
            handle.state(state_of(entry.active));
            touched = true;
        }
        if !groups[index].workspaces.contains(&entry.id) {
            groups[index].workspaces.push(entry.id);
        }
    }

    touched
}


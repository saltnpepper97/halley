//! Staging `ext-workspace-v1` workspace enumeration and activation.
//!
//! Halley's cluster model stays authoritative. This module never stores a
//! second mutable workspace model: it translates a read-only [`Snapshot`] of
//! `ClusterSystem` into protocol objects, and reduces the requests a client
//! queues before `commit` into a single [`TransactionPlan`] that the session
//! applies through its existing activation helpers.
//!
//! Two things keep this module honest:
//!
//! * Protocol state is per manager *binding*, not per client. A client may bind
//!   `ext_workspace_manager_v1` more than once and must then see independent
//!   handles for the same workspaces.
//! * Nothing here depends on `crate::`, so `tests/ext_workspace_protocol.rs`
//!   includes this file directly with `#[path]` and drives the production
//!   dispatch code over a real Wayland socket without initializing DRM or EGL.
//!
//! Protocol reference: `protocols/staging/ext-workspace/ext-workspace-v1.xml`.

use std::collections::HashMap;

use smithay::output::Output;
use smithay::reexports::wayland_protocols::ext::workspace::v1::server::{
    ext_workspace_group_handle_v1::{self, ExtWorkspaceGroupHandleV1},
    ext_workspace_handle_v1::{self, ExtWorkspaceHandleV1},
    ext_workspace_manager_v1::{self, ExtWorkspaceManagerV1},
};
use smithay::reexports::wayland_server::backend::{ClientId, GlobalId, ObjectId};
use smithay::reexports::wayland_server::protocol::wl_output::WlOutput;
use smithay::reexports::wayland_server::{
    Client, DataInit, Dispatch, DisplayHandle, GlobalDispatch, New, Resource,
};

use halley_core::cluster::ClusterId;

/// The only protocol version Halley implements.
pub const VERSION: u32 = 1;

/// `ext_workspace_group_handle_v1.group_capabilities`: empty. Halley never
/// creates workspaces on a client's behalf, so `create_workspace` is advertised
/// as unavailable and ignored if it arrives anyway.
const GROUP_CAPABILITIES: ext_workspace_group_handle_v1::GroupCapabilities =
    ext_workspace_group_handle_v1::GroupCapabilities::from_bits_retain(0);

/// `ext_workspace_handle_v1.workspace_capabilities`: `activate | deactivate`.
/// Client-driven `remove` and `assign` stay unsupported.
const WORKSPACE_CAPABILITIES: ext_workspace_handle_v1::WorkspaceCapabilities =
    ext_workspace_handle_v1::WorkspaceCapabilities::from_bits_retain(
        ext_workspace_handle_v1::WorkspaceCapabilities::Activate.bits()
            | ext_workspace_handle_v1::WorkspaceCapabilities::Deactivate.bits(),
    );

// ---------------------------------------------------------------------------
// Model snapshot
// ---------------------------------------------------------------------------

/// A read-only view of everything the protocol can see.
///
/// Generated by the session from `ClusterSystem` at the event-loop boundary and
/// compared against each binding's last advertised values. There is no second
/// mutable workspace model here.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Snapshot {
    /// One group per currently mapped output, in output order.
    pub groups: Vec<GroupSnapshot>,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct GroupSnapshot {
    /// The mapped output this group belongs to.
    ///
    /// This is the output *identity*, not only its name: a monitor that
    /// disconnects and reconnects under the same name produces a different
    /// `Output`, so stale handles can never be revived accidentally.
    pub output: Output,
    /// Advertised clusters owned by this output, in slot order. Empty
    /// workspaces still appear; a cluster is omitted only while its output is
    /// not mapped.
    pub workspaces: Vec<WorkspaceSnapshot>,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct WorkspaceSnapshot {
    pub id: ClusterId,
    /// `ClusterMetadata::name`.
    pub name: String,
    /// Published slot, 1-based. Also the source of the protocol coordinate.
    pub order: u8,
    pub active: bool,
}

/// `ext_workspace_handle_v1.coordinates` carries one coordinate per dimension.
///
/// Halley orders clusters along a single dimension, so exactly one coordinate
/// is published: the 0-based published slot, in native endianness because
/// Wayland marshals integers in host byte order.
fn coordinates(order: u8) -> Vec<u8> {
    u32::from(order.saturating_sub(1)).to_ne_bytes().to_vec()
}

fn state_of(active: bool) -> ext_workspace_handle_v1::State {
    if active {
        ext_workspace_handle_v1::State::Active
    } else {
        ext_workspace_handle_v1::State::from_bits_retain(0)
    }
}

// ---------------------------------------------------------------------------
// Requests and transactions
// ---------------------------------------------------------------------------

/// The two workspace requests Halley advertises.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum PendingAction {
    Activate,
    Deactivate,
}

/// One request queued since the last `commit`.
///
/// `remove`, `assign`, and `create_workspace` are ignored outright because
/// their capabilities are never advertised.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct PendingRequest {
    pub cluster: ClusterId,
    pub action: PendingAction,
    /// Object id of the handle the request arrived on.
    ///
    /// Carrying it lets `commit` discard a request sent on a handle that was
    /// since removed, even when the cluster itself is still advertised through
    /// a newer object.
    pub object: ObjectId,
}

/// The reduced result of one manager transaction.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct TransactionPlan {
    /// Final selection per output, in first-requested order, limited to outputs
    /// whose selection actually changes. `None` means "leave the output in
    /// Field mode".
    pub selections: Vec<(String, Option<ClusterId>)>,
    /// The single output and cluster that should take keyboard focus.
    ///
    /// A multi-output transaction still switches every changed output, but only
    /// one workspace may own the keyboard.
    pub focus: Option<(String, ClusterId)>,
}

impl TransactionPlan {
    pub fn is_empty(&self) -> bool {
        self.selections.is_empty()
    }
}

/// Reduces a transaction to the final state per output.
///
/// Requests are processed in order and the last request for an output wins.
/// `deactivate` clears a selection only when its target is the workspace that
/// would be active for that output, so deactivating an unrelated workspace
/// leaves the active selection alone. Targets are revalidated here rather than
/// trusted from queue time, which discards requests whose target disappeared
/// between the request and the commit.
pub fn reduce_transaction(
    requests: &[(ClusterId, PendingAction)],
    is_live: impl Fn(ClusterId) -> bool,
    owner_of: impl Fn(ClusterId) -> Option<String>,
    active_on: impl Fn(&str) -> Option<ClusterId>,
) -> TransactionPlan {
    let mut desired: Vec<(String, Option<ClusterId>)> = Vec::new();
    let mut last_activation: Option<(String, ClusterId)> = None;

    for (cluster, action) in requests {
        let cluster = *cluster;
        if !is_live(cluster) {
            continue;
        }
        let Some(output) = owner_of(cluster) else {
            continue;
        };
        match action {
            PendingAction::Activate => {
                set_desired(&mut desired, &output, Some(cluster));
                last_activation = Some((output, cluster));
            }
            PendingAction::Deactivate => {
                let current = desired
                    .iter()
                    .find(|(candidate, _)| *candidate == output)
                    .map(|(_, selection)| *selection)
                    .unwrap_or_else(|| active_on(&output));
                if current == Some(cluster) {
                    set_desired(&mut desired, &output, None);
                    if last_activation.as_ref() == Some(&(output.clone(), cluster)) {
                        last_activation = None;
                    }
                }
            }
        }
    }

    let selections = desired
        .into_iter()
        .filter(|(output, selection)| active_on(output) != *selection)
        .collect::<Vec<_>>();

    // Focus only the winning activation, and only when it really changed the
    // output's selection.
    let focus = last_activation.filter(|(output, cluster)| {
        selections
            .iter()
            .any(|(candidate, selection)| candidate == output && *selection == Some(*cluster))
    });

    TransactionPlan { selections, focus }
}

fn set_desired(
    desired: &mut Vec<(String, Option<ClusterId>)>,
    output: &str,
    value: Option<ClusterId>,
) {
    match desired
        .iter_mut()
        .find(|(candidate, _)| candidate == output)
    {
        Some(entry) => entry.1 = value,
        None => desired.push((output.to_string(), value)),
    }
}

